def story(
    story_id: str,
    pillar: str,
    topic: str,
    theme: str,
    perspective: str,
    protagonist: str,
    hook_type: str,
    hooks: list[str],
    hook_visual: str,
    titles: list[str],
    ending_concept: str,
    key_phrases: list[str],
    body: list[tuple[str, str]],
) -> dict[str, Any]:
    if len(body) != 7:
        raise RuntimeError(f"{story_id} must contain exactly seven post-hook beats")
    phases = ["problem", "problem", "problem", "turn", "turn", "turn", "payoff"]
    return {
        "id": story_id,
        "pillar": pillar,
        "topic": topic,
        "theme": theme,
        "perspective": perspective,
        "protagonist": protagonist,
        "hook_type": hook_type,
        "hook_candidates": hooks,
        "hook_visual": hook_visual,
        "beats": [
            {"phase": phase, "text": text, "visual_search": visual}
            for phase, (text, visual) in zip(phases, body, strict=True)
        ],
        "title_candidates": titles,
        "ending_concept": ending_concept,
        "key_phrases": key_phrases,
        "music_searches": MUSIC_BY_PILLAR[pillar],
    }


